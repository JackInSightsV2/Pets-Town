import test from 'node:test';
import assert from 'node:assert/strict';
import type { OfficeEvent, OfficeHandoff } from '../shared/contract';
import { createHandoffStore } from './handoffs';
import { agent, event, snapshot, time } from './test-helpers';

const handoff = (id: string): OfficeHandoff => ({ handoffId: id, fromAgentId: 'main', toAgentId: 'child',
  summary: 'Observed message', occurredAt: time, sourceItemId: `item-${id}` });
const observed = (seq: number, id: string) => event(seq, 'handoff.observed', { handoff: handoff(id) });

test('handoff store delivers once, publishes stable queue state, and cancels safely across visibility and reconnect', () => {
  const store = createHandoffStore();
  let officeUpdates = 0;
  let meetingUpdates = 0;
  store.subscribe(() => { officeUpdates++; });
  const unsubscribe = store.subscribeMeetings(() => { meetingUpdates++; });
  const initial = snapshot();
  initial.agents = [agent(), agent('child')];
  initial.presentation = { state: 'live', canSkip: false };
  initial.capabilities.observeHandoffs = { supported: true, reason: null };
  initial.recentHandoffs = [handoff('history')];
  const empty = store.getMeetingState();
  store.setVisibleAgents(['main', 'child']);
  store.applySnapshot(initial);
  assert.equal(officeUpdates, 1);
  assert.equal(store.getMeetingState(), empty);
  store.applyEvent(observed(1, 'history'));
  assert.equal(officeUpdates, 2);
  assert.equal(store.getMeetingState(), empty);
  store.applyEvent(observed(2, 'live'));
  const active = store.getMeetingState();
  assert.equal(active.active?.handoff.handoffId, 'live');
  assert.equal(Object.isFrozen(active.active?.token), true);
  store.applyEvent(observed(2, 'live'));
  assert.equal(officeUpdates, 3);
  assert.equal(store.getMeetingState(), active);
  assert.equal(meetingUpdates, 1);
  store.applyEvent(observed(3, 'next'));
  store.completeMeeting(active.active!.token);
  assert.equal(store.getMeetingState().active?.handoff.handoffId, 'next');
  assert.equal(meetingUpdates, 3);
  const beforeHidden = store.getMeetingState().active!.token;
  store.setVisibleAgents(['main']);
  assert.equal(store.getMeetingState().active, null);
  assert.equal(store.getMeetingState().hiddenSignals.length, 1);
  assert.equal(meetingUpdates, 4);
  store.setVisibleAgents(['main', 'child']);
  store.completeMeeting(beforeHidden);
  assert.equal(store.getMeetingState().active, null);

  store.applyEvent(observed(4, 'disconnect'));
  const cancelled = store.getMeetingState().active!.token;
  store.setTransportStatus('disconnected');
  assert.equal(store.getMeetingState().active, null);
  assert.deepEqual(store.getMeetingState().queued, []);
  store.applySnapshot(store.getState().snapshot!);
  store.setTransportStatus('connected');
  store.applyEvent(observed(5, 'disconnect'));
  assert.equal(store.getMeetingState().active, null);
  store.applyEvent(observed(6, 'fresh'));
  assert.equal(store.getMeetingState().active?.handoff.handoffId, 'fresh');
  store.completeMeeting(cancelled);
  assert.equal(store.getMeetingState().active?.handoff.handoffId, 'fresh');
  store.applyEvent({ invalid: true } as unknown as OfficeEvent);
  assert.match(store.getState().error!, /Invalid office event/);
  assert.equal(store.getMeetingState().active, null);
  const notifications = meetingUpdates;
  unsubscribe();
  store.setVisibleAgents([]);
  assert.equal(meetingUpdates, notifications);
});
